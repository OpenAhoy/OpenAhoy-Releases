def source_errors(function):
    @wraps(function)
    def checked(*args,**kwargs):
        try:return function(*args,**kwargs)
        except SourceHold as error:
            code=getattr(error,'code',None)
            if type(error)is not SourceHold or type(code)is not str or code not in KNOWN_SOURCE_HOLDS:
                code='SLOT_SOURCE_VALIDATION_HOLD'
            raise WCEError(code) from None
    return checked
